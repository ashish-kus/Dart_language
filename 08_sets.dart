void main() {
  //==============================================================
  // DART SET - COMPLETE GUIDE
  //
  // A Set is an unordered collection of UNIQUE elements.
  //
  // Characteristics:
  // ✔ No duplicate values
  // ✔ Unordered (don't rely on index positions)
  // ✔ Fast lookup (contains)
  //
  // Similar to:
  // C++  -> unordered_set
  // Java -> HashSet
  // Python -> set
  //==============================================================

  //==============================================================
  // 1. Creating a Set
  //==============================================================

  Set<int> numbers = {10, 20, 30, 40};

  print("1. Original Set");
  print(numbers);

  //==============================================================
  // 2. Empty Set
  //
  // NOTE:
  // {} creates a Map, NOT a Set.
  //==============================================================

  Set<String> names = {};

  print("\n2. Empty Set");
  print(names);

  //==============================================================
  // 3. Duplicate values are ignored
  //==============================================================

  Set<int> duplicate = {1, 2, 2, 3, 3, 4};

  print("\n3. Duplicate Values");
  print(duplicate);

  // Output:
  // {1,2,3,4}

  //==============================================================
  // 4. add()
  // Adds one element.
  //==============================================================

  print("\n4. add()");

  numbers.add(50);

  print(numbers);

  //==============================================================
  // 5. addAll()
  // Adds multiple elements.
  //==============================================================

  print("\n5. addAll()");

  numbers.addAll({60, 70, 80});

  print(numbers);

  //==============================================================
  // 6. remove()
  //==============================================================

  print("\n6. remove()");

  numbers.remove(20);

  print(numbers);

  //==============================================================
  // 7. removeAll()
  //==============================================================

  print("\n7. removeAll()");

  numbers.removeAll({40, 50});

  print(numbers);

  //==============================================================
  // 8. removeWhere()
  // Remove elements matching a condition.
  //==============================================================

  print("\n8. removeWhere()");

  numbers.removeWhere((element) => element > 60);

  print(numbers);

  //==============================================================
  // 9. contains()
  //==============================================================

  print("\n9. contains()");

  print(numbers.contains(30));

  print(numbers.contains(100));

  //==============================================================
  // 10. containsAll()
  //==============================================================

  print("\n10. containsAll()");

  print(numbers.containsAll({10, 30}));

  //==============================================================
  // 11. length
  //==============================================================

  print("\n11. length");

  print(numbers.length);

  //==============================================================
  // 12. isEmpty
  //==============================================================

  print("\n12. isEmpty");

  print(numbers.isEmpty);

  //==============================================================
  // 13. isNotEmpty
  //==============================================================

  print("\n13. isNotEmpty");

  print(numbers.isNotEmpty);

  //==============================================================
  // 14. first
  //==============================================================

  print("\n14. first");

  print(numbers.first);

  //==============================================================
  // 15. last
  //==============================================================

  print("\n15. last");

  print(numbers.last);

  //==============================================================
  // 16. single
  // Works only if Set contains exactly one element.
  //==============================================================

  print("\n16. single");

  Set<int> one = {100};

  print(one.single);

  //==============================================================
  // 17. firstWhere()
  //==============================================================

  print("\n17. firstWhere()");

  print(numbers.firstWhere((e) => e > 20));

  //==============================================================
  // 18. any()
  //==============================================================

  print("\n18. any()");

  print(numbers.any((e) => e > 50));

  //==============================================================
  // 19. every()
  //==============================================================

  print("\n19. every()");

  print(numbers.every((e) => e > 0));

  //==============================================================
  // 20. where()
  //==============================================================

  print("\n20. where()");

  var filtered = numbers.where((e) => e >= 30);

  print(filtered);

  //==============================================================
  // 21. map()
  //==============================================================

  print("\n21. map()");

  var square = numbers.map((e) => e * e);

  print(square);

  //==============================================================
  // 22. toList()
  //==============================================================

  print("\n22. toList()");

  List<int> list = numbers.toList();

  print(list);

  //==============================================================
  // 23. toSet()
  //==============================================================

  print("\n23. toSet()");

  List<int> list2 = [1, 2, 2, 3, 3, 4];

  print(list2.toSet());

  //==============================================================
  // 24. forEach()
  //==============================================================

  print("\n24. forEach()");

  numbers.forEach((element) {
    print(element);
  });

  //==============================================================
  // 25. for-in Loop
  //==============================================================

  print("\n25. for-in");

  for (var value in numbers) {
    print(value);
  }

  //==============================================================
  // 26. clear()
  //==============================================================

  print("\n26. clear()");

  Set<int> temp = {1, 2, 3};

  temp.clear();

  print(temp);

  //==============================================================
  // 27. union()
  // Combine two sets.
  //==============================================================

  print("\n27. union()");

  Set<int> a = {1, 2, 3};

  Set<int> b = {3, 4, 5};

  print(a.union(b));

  // Output:
  // {1,2,3,4,5}

  //==============================================================
  // 28. intersection()
  // Common elements.
  //==============================================================

  print("\n28. intersection()");

  print(a.intersection(b));

  // Output:
  // {3}

  //==============================================================
  // 29. difference()
  // Elements in first set but not second.
  //==============================================================

  print("\n29. difference()");

  print(a.difference(b));

  // Output:
  // {1,2}

  //==============================================================
  // 30. lookup()
  // Returns element if found, otherwise null.
  //==============================================================

  print("\n30. lookup()");

  print(a.lookup(2));

  print(a.lookup(100));

  //==============================================================
  // 31. cast()
  //==============================================================

  print("\n31. cast()");

  Set<dynamic> dynamicSet = {1, 2, 3};

  Set<int> intSet = dynamicSet.cast<int>();

  print(intSet);

  //==============================================================
  // 32. Spread Operator (...)
  //==============================================================

  print("\n32. Spread Operator");

  Set<int> c = {...a, ...b, 100};

  print(c);

  //==============================================================
  // 33. Null-aware Spread (...?)
  //==============================================================

  print("\n33. Null-aware Spread");

  Set<int>? nullableSet = null;

  Set<int> result = {...?nullableSet, 999};

  print(result);

  //==============================================================
  // 34. if Element
  //==============================================================

  print("\n34. if Element");

  bool isAdmin = true;

  Set<String> menu = {"Home", if (isAdmin) "Dashboard"};

  print(menu);

  //==============================================================
  // 35. for Element
  //==============================================================

  print("\n35. for Element");

  Set<int> doubled = {for (var x in a) x * 2};

  print(doubled);

  //==============================================================
  // 36. Constant Set
  //==============================================================

  print("\n36. Constant Set");

  const constant = {10, 20, 30};

  print(constant);

  //==============================================================
  // 37. Equality
  //
  // == checks identity for sets, not contents.
  // Use SetEquality (package:collection) if you need
  // value-based equality.
  //==============================================================

  print("\n37. Equality");

  Set<int> x = {1, 2, 3};

  Set<int> y = {1, 2, 3};

  print(x == y);

  //==============================================================
  // END
  //==============================================================
}
