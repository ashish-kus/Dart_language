void main() {
  //==============================================================
  // DART LOOPS - COMPLETE GUIDE
  //
  // Loops are used to execute a block of code repeatedly.
  //
  // Types of loops in Dart:
  // 1. for
  // 2. for-in
  // 3. forEach()
  // 4. while
  // 5. do-while
  //==============================================================

  List<int> numbers = [10, 20, 30, 40, 50];

  //==============================================================
  // 1. Simple for Loop
  //==============================================================

  print("1. Simple for Loop");

  for (int i = 0; i < 5; i++) {
    print(i);
  }

  // Output:
  // 0
  // 1
  // 2
  // 3
  // 4

  //==============================================================
  // 2. Print 1 to 10
  //==============================================================

  print("\n2. Print 1 to 10");

  for (int i = 1; i <= 10; i++) {
    print(i);
  }

  //==============================================================
  // 3. Reverse Loop
  //==============================================================

  print("\n3. Reverse Loop");

  for (int i = 10; i >= 1; i--) {
    print(i);
  }

  //==============================================================
  // 4. Loop with Step Size
  //==============================================================

  print("\n4. Increment by 2");

  for (int i = 0; i <= 10; i += 2) {
    print(i);
  }

  //==============================================================
  // 5. Access List using Index
  //==============================================================

  print("\n5. List using Index");

  for (int i = 0; i < numbers.length; i++) {
    print(numbers[i]);
  }

  //==============================================================
  // 6. for-in Loop
  //
  // Used to iterate directly over elements.
  // No index is available.
  //==============================================================

  print("\n6. for-in Loop");

  for (var number in numbers) {
    print(number);
  }

  //==============================================================
  // 7. forEach()
  //
  // Calls a function for every element.
  //==============================================================

  print("\n7. forEach()");

  numbers.forEach((number) {
    print(number);
  });

  //==============================================================
  // 8. forEach() (Short Arrow Syntax)
  //==============================================================

  print("\n8. forEach() Arrow");

  numbers.forEach((number) => print(number));

  //==============================================================
  // 9. while Loop
  //
  // Condition is checked first.
  //==============================================================

  print("\n9. while Loop");

  int i = 1;

  while (i <= 5) {
    print(i);
    i++;
  }

  //==============================================================
  // 10. do-while Loop
  //
  // Executes at least once.
  //==============================================================

  print("\n10. do-while Loop");

  int j = 1;

  do {
    print(j);
    j++;
  } while (j <= 5);

  //==============================================================
  // 11. break
  //
  // Immediately exits the loop.
  //==============================================================

  print("\n11. break");

  for (int i = 1; i <= 10; i++) {
    if (i == 6) {
      break;
    }

    print(i);
  }

  // Output:
  // 1 2 3 4 5

  //==============================================================
  // 12. continue
  //
  // Skip current iteration.
  //==============================================================

  print("\n12. continue");

  for (int i = 1; i <= 5; i++) {
    if (i == 3) {
      continue;
    }

    print(i);
  }

  // Output:
  // 1 2 4 5

  //==============================================================
  // 13. Nested Loops
  //==============================================================

  print("\n13. Nested Loops");

  for (int i = 1; i <= 3; i++) {
    for (int j = 1; j <= 3; j++) {
      print("i = $i , j = $j");
    }
  }

  //==============================================================
  // 14. Multiplication Table
  //==============================================================

  print("\n14. Table of 5");

  for (int i = 1; i <= 10; i++) {
    print("5 x $i = ${5 * i}");
  }

  //==============================================================
  // 15. Sum of Numbers
  //==============================================================

  print("\n15. Sum");

  int sum = 0;

  for (int i = 1; i <= 10; i++) {
    sum += i;
  }

  print(sum);

  //==============================================================
  // 16. Iterate over String
  //==============================================================

  print("\n16. String Characters");

  String name = "Ashish";

  for (int i = 0; i < name.length; i++) {
    print(name[i]);
  }

  //==============================================================
  // 17. Loop through Map
  //==============================================================

  print("\n17. Map using entries");

  Map<String, int> marks = {"Ashish": 90, "Rahul": 80, "Priya": 95};

  for (var entry in marks.entries) {
    print("${entry.key} -> ${entry.value}");
  }

  //==============================================================
  // 18. Loop through Keys
  //==============================================================

  print("\n18. Keys");

  for (var key in marks.keys) {
    print(key);
  }

  //==============================================================
  // 19. Loop through Values
  //==============================================================

  print("\n19. Values");

  for (var value in marks.values) {
    print(value);
  }

  //==============================================================
  // 20. asMap()
  //
  // Gives both index and value.
  //==============================================================

  print("\n20. List Index and Value");

  numbers.asMap().forEach((index, value) {
    print("Index = $index Value = $value");
  });

  //==============================================================
  // 21. Infinite Loop (Example)
  //
  // Don't run this.
  //==============================================================

  /*
  for (;;) {
    print("Infinite Loop");
  }
  */

  //==============================================================
  // 22. Infinite while Loop
  //
  // Don't run this.
  //==============================================================

  /*
  while (true) {
    print("Runs Forever");
  }
  */

  //==============================================================
  // END
  //==============================================================
}
